import { outcomes, drawGenome, rng, crossChild, podOf, countOn, kinOf, refuses } from "./engine.mjs";
const r = rng("check");
console.log("M 1x1 k0", outcomes("M", 1, 1, 0).map((x) => x.toFixed(3)).join(" "));
console.log("M 1x1 k.125", outcomes("M", 1, 1, 0.125).map((x) => x.toFixed(3)).join(" "));
console.log("M 2x1 k0", outcomes("M", 2, 1, 0).map((x) => x.toFixed(3)).join(" "));
console.log("C 1x0 k0", outcomes("C", 1, 0, 0).map((x) => x.toFixed(3)).join(" "));
const a = { id: 1, genome: drawGenome(r, { kind: "wild" }), parents: [] }, b = { id: 2, genome: drawGenome(r, { kind: "wild" }), parents: [] };
const recs = new Map([[1, a], [2, b]]);
const lookup = (id) => recs.get(id) ?? null;
let t0 = Date.now();
let n = 0;
for (let i = 0; i < 200; i++) if (crossChild(a, b, r, lookup)) n++;
console.log("200 children", n, "built in ms", Date.now() - t0);
const pod = podOf(a, r);
console.log("pod", pod ? countOn(pod, "M") : null, "a M", countOn(a.genome, "M"));
const g = crossChild(a, b, r, lookup);
const c = { id: 3, genome: g, parents: [1, 2] };
recs.set(3, c);
console.log("kin a,b", kinOf(a, b, lookup), "a,c refuses", refuses(a, c, lookup), "b,a", refuses(b, a, lookup));
