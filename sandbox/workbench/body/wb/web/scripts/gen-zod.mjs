// The build step from the species file's JSON Schema to zod and TS types (R3): src/generated/mb-species-{1,2}.schema.json (written by wb/schema_json.py, the server's
// GET /api/schema/mb-species-2) become src/generated/species.zod.ts. Run `npm run gen`; `npm test` fails when the committed output is not what this makes.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { jsonSchemaToZod } from 'json-schema-to-zod'

const dir = join(import.meta.dirname, '../src/generated')

export function generate() {
  let out = '// Generated by scripts/gen-zod.mjs from mb-species-{1,2}.schema.json: do not edit.\nimport { z } from "zod"\n\n'
  for (const [slug, name] of [['mb-species-1', 'speciesV1'], ['mb-species-2', 'speciesV2']]) {
    const schema = JSON.parse(readFileSync(join(dir, `${slug}.schema.json`), 'utf8'))
    const code = jsonSchemaToZod(schema, { name, module: 'esm', type: true, noImport: true })
    out += code.replace(/^import .*\n+/m, '') + '\n'
  }
  return out
}

if (process.argv[1] === import.meta.filename) writeFileSync(join(dir, 'species.zod.ts'), generate())
