#!/usr/bin/env node
// Snapshots the v1 authoring catalogue (catalogue6: 114 validated pairs and six drafts) into
// framework/catalogue6-data.mjs so the workbench runs in a browser and in Node without the
// v1 package graph. Provenance: the v1 module, its foundation pin digest and every record's
// own fields are carried verbatim. Run from the repository root:
//
//   node prototypes/workbench/tools/snapshot-v1-catalogue.mjs
//
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "../../..");
const v1 = path.join(repo, "v1/prototype/generator-workbench");
const { innateProfilePackage } = await import(path.join(v1, "innate-profile-package.mjs"));

const pkg = innateProfilePackage();
const cat = pkg.catalogue;
const loci = cat.loci.map((l) => ({
  id: l.id, status: l.status, family: l.family, label: l.label, target: l.target ?? null,
  operator: l.operator, units: l.units ?? null, version: l.version,
  alleles: (l.alleles || []).map((a) => ({ id: a.id, label: a.label ?? a.id, value: a.value })),
  pairMap: l.pairMap ?? null, requires: l.requires ?? [], applicability: l.applicability ?? null,
  bounds: Array.isArray(l.bounds) ? l.bounds : null,
}));
const data = {
  source: "v1/prototype/generator-workbench/innate-profile-package.mjs#innateProfilePackage().catalogue",
  id: cat.id, version: cat.version, foundationDigest: pkg.foundation.digest,
  families: cat.families.map((f) => ({ id: f.id, label: f.label ?? f.id })),
  loci,
  defaults: pkg.defaultGeneration.genome.loci,
  context: pkg.referenceContext,
};
const out = path.join(here, "../framework/catalogue6-data.mjs");
writeFileSync(out, `// Generated by tools/snapshot-v1-catalogue.mjs from ${data.source}.\n// Catalogue ${data.id}@${data.version}, foundation digest ${data.foundationDigest}. Do not edit by hand.\nexport const CATALOGUE6 = ${JSON.stringify(data, null, 1)};\n`);
console.log(`wrote ${path.relative(repo, out)}: ${loci.filter((l) => l.status === "validated").length} validated, ${loci.filter((l) => l.status !== "validated").length} drafts`);
