export const supplement = Object.freeze(Object.fromEntries(Object.entries(rows).map(([key, value]) => [key, Object.freeze(value.split('/'))])));
export function supported(character) { return Object.hasOwn(supplement, character) || Object.hasOwn(glyphs, character); }
export function glyph(character) { return supplement[character] ?? glyphs[character] ?? missingGlyph; }

export function drawText(surface, value, x, y, cells, color = 1) {
  if ([...value].length > cells) throw new Error('Transfer text overflows its region: ' + value);
  let advance = 0;
  for (const character of value) {
    const bitmap = glyph(character);
    for (let row = 0; row < 7; row++) {
      for (let column = 0; column < 5; column++) {
        if (bitmap[row][column] === '1') surface.rect(x + advance + column * 2, y + row * 2, 2, 2, color);
      }
    }
    advance += 12;
  }
}
