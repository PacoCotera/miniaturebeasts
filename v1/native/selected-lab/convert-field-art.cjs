// Measured field PNG derivatives -> immutable native straight-RGBA descriptors.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const sharp = require('sharp');
const artRoot = path.resolve(__dirname,'../../design/core-v1-art/field');
const manifestPath = path.join(artRoot,'manifest.json');
const manifest = JSON.parse(fs.readFileSync(manifestPath,'utf8'));
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const assets = [
  ['grass-a','GRASS_A'],['grass-b','GRASS_B'],['moss','MOSS'],['water','WATER'],
  ['stone','STONE'],['shrub-ground','SHRUB'],['tree-ground','TREE'],['boulder-ground','BOULDER'],
  ...Array.from({length:16},(_,mask)=>[`path-${mask}`,`PATH_${mask}`]),
  ['camp','CAMP'],['relay','RELAY'],['stone-shelf','STONE_SHELF'],
  ['moss-bend','MOSS_BEND'],['cache','CACHE']
];

async function main() {
  const source = fs.readFileSync(path.join(artRoot,manifest.source));
  if(hash(source)!==manifest.sourceSha256) throw new Error('Preserved Gemini source hash mismatch');
  const definitions=['/* Generated by convert-field-art.cjs; measured sources in design/core-v1-art/field. */','#include "field_art.h"'];
  const descriptors=[];
  const nativeRecords=[];
  for(const [name,id] of assets) {
    const record=manifest.assets.find(asset=>asset.name===name);
    if(!record) throw new Error(`Missing field derivative ${name}`);
    const png=fs.readFileSync(path.join(artRoot,record.file));
    if(hash(png)!==record.pngSha256) throw new Error(`PNG changed: ${name}`);
    const {data,info}=await sharp(png).ensureAlpha().raw().toBuffer({resolveWithObject:true});
    if(info.width!==32||info.height!==32||info.channels!==4||hash(data)!==record.rgbaSha256) throw new Error(`Native RGBA changed: ${name}`);
    const identifier=name.replaceAll('-','_');
    const lines=[];
    for(let offset=0;offset<data.length;offset+=32) lines.push('  '+Array.from(data.subarray(offset,offset+32)).join(', ')+',');
    definitions.push(`static const uint8_t ${identifier}_rgba[] = {\n${lines.join('\n')}\n};`);
    descriptors.push(`  {"${name}", 32, 32, ${identifier}_rgba, "gemini-field-atlas", "${manifest.sourceSha256}", 16, 16}`);
    nativeRecords.push({id:`FIELD_ART_${id}`,name,pngSha256:record.pngSha256,rgbaSha256:record.rgbaSha256,nativeBytes:data.length});
  }
  definitions.push(`const CoreArtSprite field_art_sprites[FIELD_ART_COUNT] = {\n${descriptors.join(',\n')}\n};`);
  definitions.push('const CoreArtSprite *field_art_sprite(FieldArtId id) {\n  return (unsigned)id < FIELD_ART_COUNT ? &field_art_sprites[id] : 0;\n}\n');
  const header=['#ifndef CRITTER_LAB_FIELD_ART_H','#define CRITTER_LAB_FIELD_ART_H','#include "core_art.h"','#define FIELD_ART_HAS_BRIDGE 0','',
    '/* Immutable 32px presentation assets; N=1, E=2, S=4, W=8 path bits come only from permitted paths. */',
    'typedef enum {',...assets.map(([,id])=>`  FIELD_ART_${id},`),'  FIELD_ART_COUNT','} FieldArtId;','',
    '/* PATH_0 is ordinary ground fallback, not invented isolated walkability. */',
    'extern const CoreArtSprite field_art_sprites[FIELD_ART_COUNT];',
    'const CoreArtSprite *field_art_sprite(FieldArtId id);','', '#endif',''];
  fs.writeFileSync(path.join(__dirname,'field_art.h'),header.join('\n'));
  fs.writeFileSync(path.join(__dirname,'field_art.c'),definitions.join('\n\n'));
  fs.writeFileSync(path.join(artRoot,'native-export-manifest.json'),JSON.stringify({sourceSha256:manifest.sourceSha256,manifestSha256:hash(fs.readFileSync(manifestPath)),rgbaBytes:nativeRecords.reduce((sum,asset)=>sum+asset.nativeBytes,0),assets:nativeRecords},null,2)+'\n');
  process.stdout.write(JSON.stringify({sprites:assets.length,rgbaBytes:assets.length*4096})+'\n');
}
main().catch(error=>{process.stderr.write(error.stack+'\n');process.exitCode=1;});
