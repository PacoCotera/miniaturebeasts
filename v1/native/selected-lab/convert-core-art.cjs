// Retained art candidates -> exact native RGBA tables. No game/view state.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const sharp = require('sharp');

const productRoot = path.resolve(__dirname, '../..');
const artRoot = path.join(productRoot, 'design/core-v1-art');
const manifest = JSON.parse(fs.readFileSync(path.join(artRoot, 'manifest.json'), 'utf8'));
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');

// Retained materials and Pip enter at exact footprints. Deliberately authored
// mono categories enter as provisional candidates for actual Dock inspection.
const accepted = [
  ['data-compact', 'DATA_COMPACT'], ['energy-compact', 'ENERGY_COMPACT'],
  ['essence-compact', 'ESSENCE_COMPACT'], ['data-primary', 'DATA_PRIMARY'],
  ['energy-primary', 'ENERGY_PRIMARY'], ['essence-primary', 'ESSENCE_PRIMARY'],
  ['crown-reference', 'CROWN_REFERENCE'], ['eye-ring-reference', 'EYE_RING_REFERENCE'],
  ['sample-neutral', 'SAMPLE_NEUTRAL'], ['pip-carried', 'PIP_PLAIN'],
  ['pip-marked', 'PIP_MARKED'],
  ['data-mono', 'DATA_MONO'], ['energy-mono', 'ENERGY_MONO'],
  ['essence-mono', 'ESSENCE_MONO'], ['residents-mono', 'RESIDENTS_MONO'],
  ['samples-mono', 'SAMPLES_MONO'], ['incubating-mono', 'INCUBATING_MONO'],
  ['link-mono', 'LINK_MONO'],
  ['probe-place', 'PROBE_PLACE'],
  ['research-inheritance', 'RESEARCH_INHERITANCE'],
  ['research-movement', 'RESEARCH_MOVEMENT'],
  ['research-effort', 'RESEARCH_EFFORT'],
];

async function main() {
  const definitions = ['/* Generated by convert-core-art.cjs; sources/hashes in design/core-v1-art. */', '#include "core_art.h"'];
  const declarations = [];
  const records = [];
  let rgbaBytes = 0;
  for (const [name, enumName] of accepted) {
    const asset = manifest.assets.find(candidate => candidate.name === name);
    if (!asset) throw new Error(`Missing exported candidate ${name}`);
    const filename = path.join(productRoot, asset.file);
    const bytes = fs.readFileSync(filename);
    if (hash(bytes) !== asset.pngSha256) throw new Error(`Source PNG changed: ${name}`);
    const {data, info} = await sharp(bytes).ensureAlpha().raw().toBuffer({resolveWithObject: true});
    if (info.channels !== 4 || hash(data) !== asset.rgbaSha256) throw new Error(`Decoded RGBA changed: ${name}`);
    const identifier = name.replaceAll('-', '_');
    const lines = [];
    for (let offset = 0; offset < data.length; offset += 32) {
      lines.push('  ' + Array.from(data.subarray(offset, offset + 32)).join(', ') + ',');
    }
    definitions.push(`static const uint8_t ${identifier}_rgba[] = {\n${lines.join('\n')}\n};`);
    const anchor = asset.centerAnchor || [Math.floor(info.width / 2), Math.floor(info.height / 2)];
    declarations.push(`  {"${name}", ${info.width}, ${info.height}, ${identifier}_rgba, "${asset.sourceId}", "${asset.sourceSha256}", ${anchor[0]}, ${anchor[1]}}`);
    records.push({id: `CORE_ART_${enumName}`, ...asset, nativeRgbaBytes: data.length});
    rgbaBytes += data.length;
  }
  definitions.push(`const CoreArtSprite core_art_sprites[CORE_ART_COUNT] = {\n${declarations.join(',\n')}\n};`);
  definitions.push('const CoreArtSprite *core_art_sprite(CoreArtId id) {\n  return (unsigned)id < CORE_ART_COUNT ? &core_art_sprites[id] : 0;\n}\n');
  const header = [
    '#ifndef CRITTER_LAB_CORE_ART_H', '#define CRITTER_LAB_CORE_ART_H', '#include <stdint.h>', '',
    '/* Straight RGBA, exact native footprint; no view/domain computation. */',
    'typedef struct {',
    '  const char *name;', '  unsigned width;', '  unsigned height;',
    '  const uint8_t *rgba;', '  const char *source_id;',
    '  const char *source_sha256;', '  unsigned center_x;', '  unsigned center_y;',
    '} CoreArtSprite;', '', 'typedef enum {',
    ...accepted.map(([, name]) => `  CORE_ART_${name},`),
    '  CORE_ART_COUNT', '} CoreArtId;', '',
    '/* Composition candidates; actual frame/focus fidelity still needs review. */',
    '#define CORE_ART_GRAPHITE_RGB 0x1e282fu', '#define CORE_ART_FIELD_RGB 0x202b32u',
    '#define CORE_ART_SHADOW_RGB 0x0b1821u', '#define CORE_ART_BLUE_RGB 0x2389c6u',
    '#define CORE_ART_BLUE_HIGHLIGHT_RGB 0x67cef5u', '#define CORE_ART_INK_RGB 0xd5e0e3u',
    '#define CORE_ART_SECONDARY_RGB 0xa5b6bdu', '#define CORE_ART_FOCUS_RGB 0xf1cd79u',
    '#define CORE_ART_SAVED_RGB 0xa3cda8u', '',
    'extern const CoreArtSprite core_art_sprites[CORE_ART_COUNT];',
    'const CoreArtSprite *core_art_sprite(CoreArtId id);',
    '', '#endif', '',
  ];
  fs.writeFileSync(path.join(__dirname, 'core_art.h'), header.join('\n'));
  fs.writeFileSync(path.join(__dirname, 'core_art.c'), definitions.join('\n\n'));
  fs.writeFileSync(path.join(artRoot, 'native-export-manifest.json'), JSON.stringify({
    scope: 'Nine alpha-reviewed materials, two retained Pip originals, seven provisional mono categories, one separately reviewed resampled Gemini setting and three contextual research derivatives; no screen/family/runtime approval',
    rgbaBytes, assets: records,
  }, null, 2) + '\n');
  console.log(`Generated ${accepted.length} native RGBA tables: ${rgbaBytes} bytes. No native compilation or renderer edits.`);
}

main().catch(error => {console.error(error);process.exitCode = 1;});
