// Builds out/ from tokens.json with Style Dictionary: tokens.css (web), station-palette.json (the Station), companion-colors.mjs (the Companion).
// Run: npm run build, in this folder. The outputs are committed (the pages and CI read them without an install).
import StyleDictionary from "style-dictionary";
import { fileURLToPath } from "node:url";

const here = fileURLToPath(new URL(".", import.meta.url));
const val = (t) => t.$value ?? t.value;
const colours = (dict, group) => dict.allTokens.filter((t) => t.path[0] === "color" && t.path[1] === group);

// CSS name of a token: colours drop their group (--mb-bone, --mb-sage), Companion colours keep it (--mb-companion-sage-l); the rest join their path (--mb-space-8, --mb-size-web-14, --mb-radius-6, --mb-duration-160).
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
// Every name carries the mb- prefix: the pages define their own --panel, --ink, --focus and the like with other meanings, so a bare name would collide.
const cssName = (t) => "--mb-" + (t.path[0] !== "color" ? t.path : t.path[1] === "companion" ? t.path.slice(1) : t.path.slice(2)).map(kebab).join("-");

StyleDictionary.registerFormat({
  name: "mb/css",
  format: ({ dictionary }) =>
    "/* Generated by prototypes/ui/tokens/build.mjs from tokens.json. Do not edit. */\n:root {\n" +
    dictionary.allTokens.map((t) => `  ${cssName(t)}: ${val(t)};`).join("\n") + "\n}\n",
});
// The Station's palette data: the same shape as palettes/station.json's "colours" (core colours, then the Station's own, in order).
StyleDictionary.registerFormat({
  name: "mb/station-json",
  format: ({ dictionary }) =>
    JSON.stringify({ palette: "station", colours: [...colours(dictionary, "core"), ...colours(dictionary, "station")].map((t) => [t.path[2], val(t)]) }, null, 1) + "\n",
});
// The Companion's palette: the core 48, then its three sage colours; exploration/src/data/palette.mjs hands it to the page.
StyleDictionary.registerFormat({
  name: "mb/companion-js",
  format: ({ dictionary }) =>
    "// Generated by prototypes/ui/tokens/build.mjs from tokens.json. Do not edit.\nexport const PALETTE = [\n" +
    [...colours(dictionary, "core"), ...colours(dictionary, "companion")].map((t) => `  [${JSON.stringify(t.path[2])}, ${JSON.stringify(val(t))}],`).join("\n") +
    "\n];\n",
});

const sd = new StyleDictionary({
  source: [here + "tokens.json"],
  log: { verbosity: "silent" },
  platforms: {
    web: { buildPath: here + "out/", files: [{ destination: "tokens.css", format: "mb/css" }] },
    station: { buildPath: here + "out/", files: [{ destination: "station-palette.json", format: "mb/station-json", filter: (t) => t.path[0] === "color" }] },
    companion: { buildPath: here + "out/", files: [{ destination: "companion-colors.mjs", format: "mb/companion-js", filter: (t) => t.path[0] === "color" }] },
  },
});
await sd.buildAllPlatforms();
