MARKS = {'home': (HOME, '#d89b14'),        # gold: Home's ochre key
         'vivarium': (VIVARIUM, '#5cbb4c'),# grass: Vivarium's green key
         'research': (RESEARCH, '#1f9d8f'),# teal: Research's teal key
         'library': (LIBRARY, '#a87bf3')}  # lilac: Library's violet key, light enough on the bar
out = sys.argv[1]
for name, (art, col) in MARKS.items():
    rows = [r for r in art.strip('\n').split('\n')]
    assert len(rows) == 24 and all(len(r) == 24 for r in rows), name
    rgb = tuple(int(col[i:i+2], 16) for i in (1, 3, 5))
    im = Image.new('RGBA', (24, 24), (0, 0, 0, 0))
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch == '#': im.putpixel((x, y), rgb + (255,))
    im.save(os.path.join(out, f'frame-room-{name}-24.png'))
print('ok')
