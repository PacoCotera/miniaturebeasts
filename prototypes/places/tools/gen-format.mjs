// Regenerate the JS reader/writer of the baked formats: flatc (pinned, VERSIONS.md) -> TypeScript -> esbuild (pinned) -> one ESM file
// with the flatbuffers runtime bundled in, so the sandbox page can import it without a bundler.
//   node gen-format.mjs [--out <file>]      default src/format/gen/place.mjs; `format.test.mjs` regenerates into a temp file and compares.
// flatc is found at $MB_FLATC, else on PATH.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, readdirSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const here = path.dirname(fileURLToPath(import.meta.url));
const places = path.join(here, '..');
export const FBS = path.join(places, 'src', 'format', 'place.fbs');
export const GEN = path.join(places, 'src', 'format', 'gen', 'place.mjs');

export function flatcPath() { return process.env.MB_FLATC || 'flatc'; }
export function flatcVersion() {
  try { return execFileSync(flatcPath(), ['--version'], { encoding: 'utf8' }).trim(); } catch { return null; }
}

export async function generate(outFile) {
  const tmp = mkdtempSync(path.join(os.tmpdir(), 'mb-fbs-'));
  execFileSync(flatcPath(), ['--ts', '--gen-all', '-o', tmp, FBS]);
  // flatc writes mb/places/*.ts and mb.ts; the entry re-exports every table, enum and struct
  const names = readdirSync(path.join(tmp, 'mb', 'places')).filter((f) => f.endsWith('.ts')).map((f) => f.slice(0, -3)).sort();
  const entry = names.map((n) => `export * from './mb/places/${n}.js';`).join('\n') + "\nexport { Builder, ByteBuffer } from 'flatbuffers';\n";
  const entryFile = path.join(tmp, 'entry.ts');
  writeFileSync(entryFile, entry);
  const out = await build({
    entryPoints: [entryFile], bundle: true, format: 'esm', platform: 'neutral', mainFields: ['module', 'main'], conditions: ['import', 'module'], target: 'es2022', write: false, logLevel: 'silent',
    absWorkingDir: tmp, nodePaths: [path.join(places, 'node_modules')], resolveExtensions: ['.ts', '.js'], sourcemap: false, minify: false, legalComments: 'none',
  });
  const banner = '// Generated by tools/gen-format.mjs from place.fbs (flatc and esbuild versions: prototypes/places/VERSIONS.md). Do not edit.\n';
  // esbuild's section comments carry the machine's path to node_modules: keep only the package-relative part so the file is the same everywhere
  const body = new TextDecoder().decode(out.outputFiles[0].contents).replace(/^\/\/ .*node_modules\//gm, '// ');
  const text = banner + body;
  mkdirSync(path.dirname(outFile), { recursive: true });
  writeFileSync(outFile, text);
  return text;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const i = process.argv.indexOf('--out');
  const out = i > 0 ? process.argv[i + 1] : GEN;
  generate(out).then((t) => console.log(`wrote ${out} (${t.length} bytes, flatc ${flatcVersion()})`));
}
