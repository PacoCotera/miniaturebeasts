// Snapshots the real 114-pair authoring catalogue (INNATE_CATALOGUE, version 6:
// 114 validated loci + 6 drafts) into src/catalogue-data.mjs, so the encoder,
// the decoder and the browser scan page share one plain-data copy.
// Run from this folder: node tools/extract-catalogue.mjs
import { writeFileSync } from "node:fs";

const src = new URL(
  "../../../v1/prototype/generator-workbench/innate-profile-package.mjs",
  import.meta.url,
);
const { INNATE_CATALOGUE: c } = await import(src.href);
const loci = c.loci
  .filter((l) => l.status === "validated")
  .map((l) => ({ id: l.id, alleles: l.alleles.map((a) => a.id), operator: l.operator }));
if (loci.length !== 114) throw new Error(`expected 114 validated loci, got ${loci.length}`);
const out = {
  source: "v1/prototype/generator-workbench/innate-profile-package.mjs#INNATE_CATALOGUE",
  id: c.id,
  version: c.version,
  digest: c.foundationPin?.digest ?? null,
  drafts: c.loci.filter((l) => l.status !== "validated").map((l) => l.id),
  loci,
};
const text =
  "// Generated by tools/extract-catalogue.mjs from the real catalogue. Do not edit.\n" +
  `export const CATALOGUE = ${JSON.stringify(out, null, 1)};\n`;
writeFileSync(new URL("../src/catalogue-data.mjs", import.meta.url), text);
console.log(`wrote ${loci.length} loci, digest ${out.digest}`);
