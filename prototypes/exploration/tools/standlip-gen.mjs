// Writes src/standlip.mjs: the crown of every cliff piece as TILE DATA, read from the piece files themselves (never from a screen, so the day, the night and the storm all give the same answer).
// Per piece, per pixel row: runs of t (transparent: the raised ground shows through), g (the crown's grass) and x (the rim's ink, the rock: not grass), e.g. "t14g30x4".
// Only the rows a pawn can stand beside are kept (ROWS): the rows under them are the face, all rock.
// Run again after any repaint of the cliff pieces (cliff-top-3 repaints the crowns):
//   node prototypes/exploration/tools/standlip-gen.mjs <tree>      (needs pngjs: NODE_PATH=<a tree's prototypes/places/node_modules>)
// tests/standnudge.test.mjs rebuilds the table from the piece files and fails when the committed src/standlip.mjs differs, so a repaint without this script fails CI.
import { writeFileSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readPng } from '../../places/src/png.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
export const ROWS = 160;
export const isGrass = (r, g, b) => g - b >= 10 && g >= r - 4;   // green leads blue; the rim's ink (near black) and the rock (blue-grey) are not grass
// the pieces that draw a crown or its edge; the foot overlays (shade on the ground), the way up and the fill carry no crown
const crownKind = (k) => /^cliff-(south|corner|end1|end2|flank|back)/.test(k);

export function crownTable(tree) {
  const set = path.join(tree, 'art/places/sets/ninja-test'), out = {};
  for (const f of readdirSync(set).filter(f => f.endsWith('.png')).map(f => f.slice(0, -4)).filter(crownKind).sort()) {
    const img = readPng(path.join(set, f + '.png')), rows = [];
    for (let y = 0; y < Math.min(img.h, ROWS); y++) {
      let s = '', cur = '', n = 0;
      for (let x = 0; x < img.w; x++) {
        const i = (y * img.w + x) * 4, c = img.data[i + 3] < 128 ? 't' : isGrass(img.data[i], img.data[i + 1], img.data[i + 2]) ? 'g' : 'x';
        if (c === cur) n++; else { if (n) s += cur + n; cur = c; n = 1; }
      }
      rows.push(s + cur + n);
    }
    out[f] = { w: img.w, h: img.h, rows };
  }
  return out;
}
export const render = (t) => `// GENERATED by tools/standlip-gen.mjs from the cliff pieces of art/places/sets/ninja-test (do not edit; tests/standnudge.test.mjs checks it against the files).\n// Per piece: w, h and the first ${ROWS} pixel rows as runs: t transparent, g crown grass, x rim ink or rock.\nexport const CROWN = {\n${Object.entries(t).map(([k, v]) => `  '${k}': { w: ${v.w}, h: ${v.h}, rows: ${JSON.stringify(v.rows)} },`).join('\n')}\n};\n`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const t = crownTable(process.argv[2] || path.join(here, '../../..'));
  writeFileSync(path.join(here, '../src/standlip.mjs'), render(t));
  console.log('wrote src/standlip.mjs', Object.keys(t).length, 'pieces');
}
